`timescale 1ns/1ps

// ============================================================================
// tb_design_1.sv
//
// Vivado behavioral full-system simulation for:
//
//   Zynq UltraScale+ MPSoC VIP
//       M_AXI_HPM0_FPD
//            |
//       SmartConnect
//            |
//       cnn_0/s_axi_control
//
//   cnn_0/m_axi_gmem
//            |
//       SmartConnect
//         /      \
//        /        \
//   S_AXI_HP0_FPD  AXI BRAM Controller
//        |                |
//   PS VIP DDR      Stand Alone BMG
//                     (all_weights.coe)
//
//   Input/logits stay in DDR.
//   All CNN weights/biases are pre-initialized in one contiguous BRAM.
//
// Test vectors reproduce tb_cnn.cpp:
//   seed = 12413
//   shifts = {2,3,4,4,5,5,4}
// Expected logits from the existing C golden test:
//   [-36, 222]
//
// IMPORTANT:
//   DUT hierarchy assumes the default wrapper generated by Vivado:
//     design_1_wrapper dut();
//     dut.design_1_i.zynq_ultra_ps_e_0.inst
//
//   If your BD/wrapper/PS instance names differ, edit macro `PS_VIP below.
// ============================================================================

module tb_design_1;

    // ------------------------------------------------------------------------
    // DUT
    // ------------------------------------------------------------------------
    design_1_wrapper dut();

    // Change only this macro if your instance hierarchy is different.
    `define PS_VIP dut.design_1_i.zynq_ultra_ps_e_0.inst

    // ------------------------------------------------------------------------
    // AXI-Lite control base address from Vivado Address Editor
    // ------------------------------------------------------------------------
    localparam logic [31:0] CNN_CTRL_BASE = 32'hA000_0000;

    // Standard HLS control registers
    localparam logic [31:0] REG_AP_CTRL = 32'h0000_0000;
    localparam logic [31:0] REG_GIE     = 32'h0000_0004;
    localparam logic [31:0] REG_IER     = 32'h0000_0008;
    localparam logic [31:0] REG_ISR     = 32'h0000_000C;

    // ------------------------------------------------------------------------
    // HLS AXI-Lite register map
    //
    // 18 pointer arguments, each 64-bit:
    //   low32, high32, reserved => 0x0C bytes each
    //
    // Then 7 int scalar shift arguments:
    //   data32, reserved => 0x08 bytes each
    // ------------------------------------------------------------------------
    localparam logic [31:0] REG_INPUT      = 32'h0000_0010;
    localparam logic [31:0] REG_WEIGHT1_1  = 32'h0000_001C;
    localparam logic [31:0] REG_BIAS1_1    = 32'h0000_0028;
    localparam logic [31:0] REG_WEIGHT1_2  = 32'h0000_0034;
    localparam logic [31:0] REG_BIAS1_2    = 32'h0000_0040;
    localparam logic [31:0] REG_WEIGHT2_1  = 32'h0000_004C;
    localparam logic [31:0] REG_BIAS2_1    = 32'h0000_0058;
    localparam logic [31:0] REG_WEIGHT2_2  = 32'h0000_0064;
    localparam logic [31:0] REG_BIAS2_2    = 32'h0000_0070;
    localparam logic [31:0] REG_WEIGHT3_1  = 32'h0000_007C;
    localparam logic [31:0] REG_BIAS3_1    = 32'h0000_0088;
    localparam logic [31:0] REG_WEIGHT3_2  = 32'h0000_0094;
    localparam logic [31:0] REG_BIAS3_2    = 32'h0000_00A0;
    localparam logic [31:0] REG_WEIGHT_FC1 = 32'h0000_00AC;
    localparam logic [31:0] REG_BIAS_FC1   = 32'h0000_00B8;
    localparam logic [31:0] REG_WEIGHT_FC2 = 32'h0000_00C4;
    localparam logic [31:0] REG_BIAS_FC2   = 32'h0000_00D0;
    localparam logic [31:0] REG_LOGITS     = 32'h0000_00DC;

    localparam logic [31:0] REG_SHIFT1_1   = 32'h0000_00E8;
    localparam logic [31:0] REG_SHIFT1_2   = 32'h0000_00F0;
    localparam logic [31:0] REG_SHIFT2_1   = 32'h0000_00F8;
    localparam logic [31:0] REG_SHIFT2_2   = 32'h0000_0100;
    localparam logic [31:0] REG_SHIFT3_1   = 32'h0000_0108;
    localparam logic [31:0] REG_SHIFT3_2   = 32'h0000_0110;
    localparam logic [31:0] REG_SHIFT_FC1  = 32'h0000_0118;

    // ------------------------------------------------------------------------
    // Memory layout
    //
    // DDR:
    //   input  -> 0x1000_0000
    //   logits -> 0x1011_0000
    //
    // BRAM:
    //   all weights/biases are pre-initialized from all_weights.coe
    //   in one contiguous address space starting at 0xE000_0000.
    //
    // Vivado Address Editor should map the BRAM segment as:
    //   Base  = 0xE000_0000
    //   Range = 128K
    // ------------------------------------------------------------------------
    localparam logic [31:0] DDR_INPUT      = 32'h1000_0000;
    localparam logic [31:0] DDR_LOGITS     = 32'h1011_0000;

    localparam logic [31:0] BRAM_WEIGHT1_1  = 32'hE000_0000;
    localparam logic [31:0] BRAM_BIAS1_1    = 32'hE000_0090;
    localparam logic [31:0] BRAM_WEIGHT1_2  = 32'hE000_00D0;
    localparam logic [31:0] BRAM_BIAS1_2    = 32'hE000_09D0;
    localparam logic [31:0] BRAM_WEIGHT2_1  = 32'hE000_0A10;
    localparam logic [31:0] BRAM_BIAS2_1    = 32'hE000_1C10;
    localparam logic [31:0] BRAM_WEIGHT2_2  = 32'hE000_1C90;
    localparam logic [31:0] BRAM_BIAS2_2    = 32'hE000_4090;
    localparam logic [31:0] BRAM_WEIGHT3_1  = 32'hE000_4110;
    localparam logic [31:0] BRAM_BIAS3_1    = 32'hE000_8910;
    localparam logic [31:0] BRAM_WEIGHT3_2  = 32'hE000_8A10;
    localparam logic [31:0] BRAM_BIAS3_2    = 32'hE001_1A10;
    localparam logic [31:0] BRAM_WEIGHT_FC1 = 32'hE001_1B10;
    localparam logic [31:0] BRAM_BIAS_FC1   = 32'hE001_2B10;
    localparam logic [31:0] BRAM_WEIGHT_FC2 = 32'hE001_2C10;
    localparam logic [31:0] BRAM_BIAS_FC2   = 32'hE001_2C90;

    // ------------------------------------------------------------------------
    // Exact model sizes from cnn_top.h
    // ------------------------------------------------------------------------
    localparam integer N_INPUT      = 400 * 64;          // 25,600 int8
    localparam integer N_W1_1       = 3 * 3 * 1  * 16;  // 144 int8
    localparam integer N_B1_1       = 16;                // int32
    localparam integer N_W1_2       = 3 * 3 * 16 * 16;  // 2,304 int8
    localparam integer N_B1_2       = 16;
    localparam integer N_W2_1       = 3 * 3 * 16 * 32;  // 4,608 int8
    localparam integer N_B2_1       = 32;
    localparam integer N_W2_2       = 3 * 3 * 32 * 32;  // 9,216 int8
    localparam integer N_B2_2       = 32;
    localparam integer N_W3_1       = 3 * 3 * 32 * 64;  // 18,432 int8
    localparam integer N_B3_1       = 64;
    localparam integer N_W3_2       = 3 * 3 * 64 * 64;  // 36,864 int8
    localparam integer N_B3_2       = 64;
    localparam integer N_W_FC1      = 64 * 64;           // 4,096 int8
    localparam integer N_B_FC1      = 64;
    localparam integer N_W_FC2      = 64 * 2;            // 128 int8
    localparam integer N_B_FC2      = 2;
    localparam integer N_LOGITS     = 2;

    localparam integer signed EXPECTED_LOGIT0 = -36;
    localparam integer signed EXPECTED_LOGIT1 = 222;

    // ------------------------------------------------------------------------
    // VIP transaction variables
    // ------------------------------------------------------------------------
    logic [1:0]    axi_resp;
    logic [127:0]  axi_rd_data;
    logic [1023:0] ddr_data;

    logic [31:0] rng_state;

    integer signed got_logit0;
    integer signed got_logit1;

    // ------------------------------------------------------------------------
    // Deterministic LCG: exact uint32_t wraparound used by tb_cnn.cpp
    // ------------------------------------------------------------------------
    function automatic logic [31:0] lcg_next(input logic [31:0] s);
        logic [63:0] t;
        begin
            t = ({32'd0, s} * 64'd1664525) + 64'd1013904223;
            lcg_next = t[31:0];
        end
    endfunction


    // ------------------------------------------------------------------------
    // Advance the deterministic RNG without writing data.
    //
    // All weights/biases now come from pre-initialized BRAM (all_weights.coe).
    // The original RNG consumption order must still be preserved exactly so
    // that the deterministic test remains identical to tb_cnn.cpp.
    // ------------------------------------------------------------------------
    task automatic rng_skip(input integer count);
        integer i;
        begin
            for (i = 0; i < count; i = i + 1)
                rng_state = lcg_next(rng_state);
        end
    endtask

    // ------------------------------------------------------------------------
    // PS VIP reset sequence.
    // DS941 requires por_srstb_reset() before any VIP read/write API.
    // ------------------------------------------------------------------------
    task automatic vip_reset;
        begin
            $display("[%0t] VIP reset...", $time);

            `PS_VIP.por_srstb_reset(1'b1);
            #200;
            `PS_VIP.por_srstb_reset(1'b0);
            `PS_VIP.fpga_soft_reset(4'hF);
            #400;

            // DS941: allow at least 16 PL clock pulses before releasing.
            `PS_VIP.por_srstb_reset(1'b1);
            `PS_VIP.fpga_soft_reset(4'h0);

            // Give PL clock/reset generation time to settle.
            #2000;

            $display("[%0t] VIP reset done.", $time);
        end
    endtask

    // ------------------------------------------------------------------------
    // AXI-Lite helpers: traffic goes PS M_AXI_HPM0_FPD -> cnn s_axi_control.
    // ------------------------------------------------------------------------
    task automatic axi_write32(
        input logic [31:0] addr,
        input logic [31:0] data
    );
        begin
            axi_resp = 2'b00;
            `PS_VIP.write_data(addr, 8'd4, data, axi_resp);

            if (axi_resp !== 2'b00) begin
                $fatal(1,
                    "[%0t] AXI write failed addr=0x%08h data=0x%08h resp=%0b",
                    $time, addr, data, axi_resp);
            end
        end
    endtask

    task automatic axi_read32(
        input  logic [31:0] addr,
        output logic [31:0] data
    );
        logic [31:0] aligned_addr;
        integer bit_offset;
        begin
            axi_resp    = 2'b00;
            axi_rd_data = '0;

            // Read one complete 128-bit (16-byte) HPM beat from a 16-byte
            // aligned address, then select the requested 32-bit byte lane.
            //
            // Example:
            //   addr = 0xA0000118
            //   aligned_addr = 0xA0000110
            //   bit_offset = 8*8 = 64
            //   result = axi_rd_data[95:64]
            aligned_addr = {addr[31:4], 4'b0000};

            `PS_VIP.read_data(aligned_addr, 8'd16, axi_rd_data, axi_resp);

            if (axi_resp !== 2'b00) begin
                $fatal(1,
                    "[%0t] AXI read failed addr=0x%08h aligned=0x%08h resp=%0b",
                    $time, addr, aligned_addr, axi_resp);
            end

            bit_offset = addr[3:0] * 8;
            data = axi_rd_data[bit_offset +: 32];
        end
    endtask

    task automatic axi_write64(
        input logic [31:0] reg_offset,
        input logic [63:0] value
    );
        begin
            axi_write32(CNN_CTRL_BASE + reg_offset,
                        value[31:0]);
            axi_write32(CNN_CTRL_BASE + reg_offset + 32'd4,
                        value[63:32]);
        end
    endtask

    // ------------------------------------------------------------------------
    // DDR backdoor fill helpers.
    //
    // write_mem() supports up to 128 bytes per call. Packing uses:
    //   lowest-address byte -> data[7:0]
    // which matches little-endian CPU/HLS memory layout.
    // ------------------------------------------------------------------------
    task automatic ddr_fill_rand_i8(
        input logic [31:0] base_addr,
        input integer      count,
        input integer      modulo,
        input integer      subtract_value
    );
        integer i;
        integer j;
        integer chunk;
        integer signed value;
        logic [1023:0] wr;
        begin
            i = 0;

            while (i < count) begin
                chunk = count - i;
                if (chunk > 128)
                    chunk = 128;

                wr = '0;

                for (j = 0; j < chunk; j = j + 1) begin
                    rng_state = lcg_next(rng_state);
                    value = ($unsigned(rng_state) % modulo) - subtract_value;
                    wr[(j*8) +: 8] = value[7:0];
                end

                `PS_VIP.write_mem(wr, base_addr + i, chunk);
                i = i + chunk;
            end
        end
    endtask

    task automatic ddr_fill_rand_i32(
        input logic [31:0] base_addr,
        input integer      count,
        input integer      modulo,
        input integer      subtract_value
    );
        integer i;
        integer j;
        integer chunk_words;
        integer signed value;
        logic [1023:0] wr;
        begin
            i = 0;

            while (i < count) begin
                chunk_words = count - i;
                if (chunk_words > 32)
                    chunk_words = 32;

                wr = '0;

                for (j = 0; j < chunk_words; j = j + 1) begin
                    rng_state = lcg_next(rng_state);
                    value = ($unsigned(rng_state) % modulo) - subtract_value;
                    wr[(j*32) +: 32] = value[31:0];
                end

                `PS_VIP.write_mem(wr, base_addr + (i*4), chunk_words*4);
                i = i + chunk_words;
            end
        end
    endtask

    task automatic ddr_zero(
        input logic [31:0] base_addr,
        input integer      byte_count
    );
        integer i;
        integer chunk;
        logic [1023:0] wr;
        begin
            wr = '0;
            i = 0;

            while (i < byte_count) begin
                chunk = byte_count - i;
                if (chunk > 128)
                    chunk = 128;
                `PS_VIP.write_mem(wr, base_addr + i, chunk);
                i = i + chunk;
            end
        end
    endtask

    // ------------------------------------------------------------------------
    // Generate exactly the same vectors/order as tb_cnn.cpp.
    // ------------------------------------------------------------------------
    task automatic initialize_ddr_vectors;
        begin
            $display("[%0t] Initializing DDR input/output and preserving RNG sequence...", $time);

            rng_state = 32'd12413;

            // Input remains in DDR and consumes the first 25,600 RNG values.
            // input[i] = (next_rand(seed) % 17) - 8
            ddr_fill_rand_i8(DDR_INPUT, N_INPUT, 17, 8);

            // All weights/biases are already initialized in BRAM by
            // all_weights.coe. Do not write them to DDR.
            //
            // IMPORTANT: preserve the exact RNG generation order from tb_cnn.cpp.

            // Conv1_1
            rng_skip(N_W1_1);   // weights: %7 - 3
            rng_skip(N_B1_1);   // bias:    %51 - 10

            // Conv1_2
            rng_skip(N_W1_2);   // weights: %5 - 2
            rng_skip(N_B1_2);

            // Conv2_1
            rng_skip(N_W2_1);
            rng_skip(N_B2_1);

            // Conv2_2
            rng_skip(N_W2_2);
            rng_skip(N_B2_2);

            // Conv3_1
            rng_skip(N_W3_1);
            rng_skip(N_B3_1);

            // Conv3_2
            rng_skip(N_W3_2);
            rng_skip(N_B3_2);

            // FC generation order in the original testbench is:
            //   weight_fc1 -> weight_fc2 -> bias_fc1 -> bias_fc2
            // This order is intentionally kept even though the physical BRAM
            // layout places each bias next to its corresponding weight tensor.
            rng_skip(N_W_FC1);  // %7 - 3
            rng_skip(N_W_FC2);  // %7 - 3
            rng_skip(N_B_FC1);  // %251 - 75
            rng_skip(N_B_FC2);  // %201 - 100

            // Known initial output area remains in DDR.
            ddr_zero(DDR_LOGITS, N_LOGITS * 4);

            $display("[%0t] DDR input/output initialized; BRAM weights/biases supplied by COE.", $time);
        end
    endtask

    // ------------------------------------------------------------------------
    // Program cnn_0's generated AXI-Lite registers.
    //
    // input/logits point to DDR.
    // all weights/biases point to the combined COE-initialized BRAM.
    // All addresses fit below 4 GiB, so high word = 0.
    // ------------------------------------------------------------------------
    task automatic program_cnn_registers;
        logic [31:0] readback;
        begin
            $display("[%0t] Programming CNN registers...", $time);

            axi_write64(REG_INPUT,      {32'd0, DDR_INPUT});

            axi_write64(REG_WEIGHT1_1,  {32'd0, BRAM_WEIGHT1_1});
            axi_write64(REG_BIAS1_1,    {32'd0, BRAM_BIAS1_1});
            axi_write64(REG_WEIGHT1_2,  {32'd0, BRAM_WEIGHT1_2});
            axi_write64(REG_BIAS1_2,    {32'd0, BRAM_BIAS1_2});

            axi_write64(REG_WEIGHT2_1,  {32'd0, BRAM_WEIGHT2_1});
            axi_write64(REG_BIAS2_1,    {32'd0, BRAM_BIAS2_1});
            axi_write64(REG_WEIGHT2_2,  {32'd0, BRAM_WEIGHT2_2});
            axi_write64(REG_BIAS2_2,    {32'd0, BRAM_BIAS2_2});

            axi_write64(REG_WEIGHT3_1,  {32'd0, BRAM_WEIGHT3_1});
            axi_write64(REG_BIAS3_1,    {32'd0, BRAM_BIAS3_1});
            axi_write64(REG_WEIGHT3_2,  {32'd0, BRAM_WEIGHT3_2});
            axi_write64(REG_BIAS3_2,    {32'd0, BRAM_BIAS3_2});

            axi_write64(REG_WEIGHT_FC1, {32'd0, BRAM_WEIGHT_FC1});
            axi_write64(REG_BIAS_FC1,   {32'd0, BRAM_BIAS_FC1});
            axi_write64(REG_WEIGHT_FC2, {32'd0, BRAM_WEIGHT_FC2});
            axi_write64(REG_BIAS_FC2,   {32'd0, BRAM_BIAS_FC2});

            axi_write64(REG_LOGITS,     {32'd0, DDR_LOGITS});

            // Matches tb_cnn.cpp:
            // test_case(2, 3, 4, 4, 5, 5, 4, 12413u)
            axi_write32(CNN_CTRL_BASE + REG_SHIFT1_1,  32'd2);
            axi_write32(CNN_CTRL_BASE + REG_SHIFT1_2,  32'd3);
            axi_write32(CNN_CTRL_BASE + REG_SHIFT2_1,  32'd4);
            axi_write32(CNN_CTRL_BASE + REG_SHIFT2_2,  32'd4);
            axi_write32(CNN_CTRL_BASE + REG_SHIFT3_1,  32'd5);
            axi_write32(CNN_CTRL_BASE + REG_SHIFT3_2,  32'd5);
            axi_write32(CNN_CTRL_BASE + REG_SHIFT_FC1, 32'd4);

            // A couple of AXI-Lite readbacks catch address-map/path mistakes early.
            axi_read32(CNN_CTRL_BASE + REG_INPUT, readback);
            if (readback !== DDR_INPUT)
                $fatal(1, "INPUT pointer readback mismatch: got 0x%08h expected 0x%08h",
                       readback, DDR_INPUT);

            axi_read32(CNN_CTRL_BASE + REG_WEIGHT1_1, readback);
            if (readback !== BRAM_WEIGHT1_1)
                $fatal(1, "WEIGHT1_1 pointer readback mismatch: got 0x%08h expected 0x%08h",
                       readback, BRAM_WEIGHT1_1);

            axi_read32(CNN_CTRL_BASE + REG_WEIGHT2_2, readback);
            if (readback !== BRAM_WEIGHT2_2)
                $fatal(1, "WEIGHT2_2 pointer readback mismatch: got 0x%08h expected 0x%08h",
                       readback, BRAM_WEIGHT2_2);

            axi_read32(CNN_CTRL_BASE + REG_BIAS_FC2, readback);
            if (readback !== BRAM_BIAS_FC2)
                $fatal(1, "BIAS_FC2 pointer readback mismatch: got 0x%08h expected 0x%08h",
                       readback, BRAM_BIAS_FC2);

            axi_read32(CNN_CTRL_BASE + REG_SHIFT_FC1, readback);
            if (readback !== 32'd4)
                $fatal(1, "SHIFT_FC1 readback mismatch: got 0x%08h", readback);

            $display("[%0t] CNN registers programmed.", $time);
        end
    endtask

    // ------------------------------------------------------------------------
    // Start and wait.
    // AP_CTRL:
    //   bit0 = ap_start
    //   bit1 = ap_done  (clear-on-read)
    //   bit2 = ap_idle
    //   bit3 = ap_ready
    // ------------------------------------------------------------------------
    task automatic start_cnn;
        logic [31:0] ctrl;
        begin
            axi_read32(CNN_CTRL_BASE + REG_AP_CTRL, ctrl);
            $display("[%0t] AP_CTRL before start = 0x%08h", $time, ctrl);

            axi_write32(CNN_CTRL_BASE + REG_AP_CTRL, 32'h0000_0001);

            $display("[%0t] CNN started.", $time);
        end
    endtask

    task automatic wait_cnn_done;
        integer poll;
        logic [31:0] ctrl;
        bit done;
        begin
            done = 1'b0;

            // Expected compute time is a few ms at 100 MHz.
            // Poll every 10 us; allow up to 50 ms for full-system RTL simulation.
            for (poll = 0; poll < 5000; poll = poll + 1) begin
                #10000;
                axi_read32(CNN_CTRL_BASE + REG_AP_CTRL, ctrl);

                if (ctrl[1]) begin
                    done = 1'b1;
                    $display("[%0t] CNN done after %0d polls, AP_CTRL=0x%08h",
                             $time, poll + 1, ctrl);
                    break;
                end
            end

            if (!done)
                $fatal(1, "[%0t] TIMEOUT waiting for CNN ap_done", $time);
        end
    endtask

    // ------------------------------------------------------------------------
    // Read logits directly from PS VIP DDR model after CNN writes them via HP0.
    // ------------------------------------------------------------------------
    task automatic read_logits_words(output logic signed [31:0] first_word,
                                     output logic signed [31:0] second_word);
        begin
            `PS_VIP.read_mem(DDR_LOGITS, 4, ddr_data);
            first_word = $signed(ddr_data[31:0]);
            `PS_VIP.read_mem(DDR_LOGITS + 32'd4, 4, ddr_data);
            second_word = $signed(ddr_data[31:0]);
        end
    endtask

    task automatic read_and_check_logits;
        begin
            read_logits_words(got_logit0, got_logit1);
            $display("[%0t] immediate 4+4 B = [%0d, %0d]", $time, got_logit0, got_logit1);

            #1000;  // 1 us with the testbench timescale
            read_logits_words(got_logit0, got_logit1);
            $display("[%0t] delayed   4+4 B = [%0d, %0d]", $time, got_logit0, got_logit1);

            // Compare the two read widths at the same simulation time.
            // The golden check below uses the delayed individual words.
            `PS_VIP.read_mem(DDR_LOGITS, 8, ddr_data);
            $display("[%0t] delayed   8 B raw = %016h", $time, ddr_data[63:0]);

            $display("------------------------------------------------------------");
            $display("RTL/Vivado logits = [%0d, %0d]", got_logit0, got_logit1);
            $display("CPU golden logits = [%0d, %0d]",
                     EXPECTED_LOGIT0, EXPECTED_LOGIT1);
            $display("------------------------------------------------------------");

            if ((got_logit0 !== EXPECTED_LOGIT0) ||
                (got_logit1 !== EXPECTED_LOGIT1)) begin
                $fatal(1,
                    "FAIL: logits mismatch. got=[%0d,%0d] expected=[%0d,%0d]",
                    got_logit0, got_logit1,
                    EXPECTED_LOGIT0, EXPECTED_LOGIT1);
            end

            $display("PASS: full Vivado PS + AXI + DDR + COE-BRAM + CNN simulation.");
        end
    endtask

    // ------------------------------------------------------------------------
    // Main
    // ------------------------------------------------------------------------
    initial begin
        $display("");
        $display("============================================================");
        $display(" CNN Full-System Vivado Behavioral Simulation");
        $display(" seed=12413, shifts={2,3,4,4,5,5,4}");
        $display("============================================================");

        // Mandatory before any PS VIP API.
        vip_reset();

        // Limit VIP transaction logging during the full-frame functional test.
        `PS_VIP.set_debug_level_info(1'b0);

        // Use the HP0 model's best-case response latency for this run.
        `PS_VIP.set_slave_profile("S_AXI_HP0_FPD", 2'b00);

        initialize_ddr_vectors();
        program_cnn_registers();
        start_cnn();
        wait_cnn_done();
        read_and_check_logits();

        #1000;
        $finish;
    end

endmodule
